// NFC-normalized like normalizePathnameForCompare: macOS reports NFD paths
// from disk while renderer-built paths are NFC; comparing without unicode
// normalization left duplicate sidebar rows after rename/drag of items with
// Persian/accented names (a second index node under the other form).
const normalizeIndexPathKey = (pathname) => normalizePathnameForCompare(pathname);

// uidByPathname is the O(1) pathname -> uid lookup for the index. Every
// mutation of nodesByUid / node.pathname must go through the helpers below —
// scanning nodesByUid per lookup (inside immer reducers) froze the renderer
// for seconds on ~11.5k-node collections during hydration/resequence/move.
const ensureUidByPathname = (index) => {
  if (!index.uidByPathname) {
    // Index created before the map existed — build it once.
    index.uidByPathname = {};
    for (const node of Object.values(index.nodesByUid || {})) {
      index.uidByPathname[normalizeIndexPathKey(node.pathname)] = node.uid;
    }
  }
  return index.uidByPathname;
};

const setIndexNode = (index, node) => {
  index.nodesByUid[node.uid] = node;
  ensureUidByPathname(index)[normalizeIndexPathKey(node.pathname)] = node.uid;
};

const deleteIndexNode = (index, node) => {
  delete index.nodesByUid[node.uid];
  const map = ensureUidByPathname(index);
  const key = normalizeIndexPathKey(node.pathname);
  if (map[key] === node.uid) {
    delete map[key];
  }
};

const rekeyIndexNodePathname = (index, node, previousPathname) => {
  const map = ensureUidByPathname(index);
  const previousKey = normalizeIndexPathKey(previousPathname);
  if (map[previousKey] === node.uid) {
    delete map[previousKey];
  }
  map[normalizeIndexPathKey(node.pathname)] = node.uid;
};

// Collect a node and its descendants via childrenByParentUid (O(subtree)),
// replacing the previous full-index pathname-prefix scans.
const collectIndexSubtreeNodes = (index, rootNode) => {
  const result = [];
  const stack = [rootNode.uid];
  while (stack.length) {
    const uid = stack.pop();
    const node = index.nodesByUid[uid];
    if (!node) {
      continue;
    }
    result.push(node);
    for (const childUid of index.childrenByParentUid[uid] || []) {
      stack.push(childUid);
    }
  }
  return result;
};

const appendChildUid = (index, parentUid, uid) => {
  const parentKey = parentUid || 'root';
  if (!index.childrenByParentUid[parentKey]) {
    index.childrenByParentUid[parentKey] = [];
  }

  if (!index.childrenByParentUid[parentKey].includes(uid)) {
    index.childrenByParentUid[parentKey].push(uid);
  }

  if (!parentUid && !index.rootChildUids.includes(uid)) {
    index.rootChildUids.push(uid);
  }
};

const removeChildUid = (index, parentUid, uid) => {
  const parentKey = parentUid || 'root';
  if (index.childrenByParentUid[parentKey]) {
    index.childrenByParentUid[parentKey] = index.childrenByParentUid[parentKey].filter((childUid) => childUid !== uid);
  }

  if (!parentUid) {
    index.rootChildUids = index.rootChildUids.filter((childUid) => childUid !== uid);
  }
};

const findIndexNodeByPathname = (index, pathname) => {
  if (!index?.nodesByUid) {
    return undefined;
  }
  const uid = ensureUidByPathname(index)[normalizeIndexPathKey(pathname)];
  return uid ? index.nodesByUid[uid] : undefined;
};

const upsertCollectionIndexNodeFromItem = (state, collectionUid, item) => {
  const index = state.collectionIndexes?.[collectionUid];
  if (!index || !item?.uid || !item?.pathname) {
    return;
  }

  const parentPathname = path.dirname(item.pathname);
  const parentNode = findIndexNodeByPathname(index, parentPathname);
  const existingNode = index.nodesByUid[item.uid] || findIndexNodeByPathname(index, item.pathname);
  const previousParentUid = existingNode?.parentUid || null;
  const parentUid = parentNode?.uid || null;
  const request = item.draft?.request || item.request || {};

  if (existingNode?.uid && existingNode.uid !== item.uid) {
    // The same pathname is being re-indexed under a new uid — e.g. eager
    // hydration (phase 2) upserts a folder from the renderer tree whose item
    // uid differs from the indexer's. Migrate the old node's children onto the
    // new uid instead of deleting the node and STRANDING them: deleteIndexNode
    // does not touch childrenByParentUid[oldUid], so a folder whose children
    // were correctly linked by the indexer would otherwise render empty even
    // though the files are on disk (the "سرویس بیمه opens empty" bug).
    const strandedChildren = index.childrenByParentUid[existingNode.uid] || [];
    if (strandedChildren.length) {
      const target = index.childrenByParentUid[item.uid] || [];
      for (const childUid of strandedChildren) {
        const child = index.nodesByUid[childUid];
        if (child) {
          child.parentUid = item.uid;
        }
        if (!target.includes(childUid)) {
          target.push(childUid);
        }
      }
      index.childrenByParentUid[item.uid] = target;
    }
    delete index.childrenByParentUid[existingNode.uid];
    removeChildUid(index, existingNode.parentUid, existingNode.uid);
    deleteIndexNode(index, existingNode);
  }

  if (previousParentUid !== parentUid) {
    removeChildUid(index, previousParentUid, item.uid);
  }

  const currentNode = index.nodesByUid[item.uid];
  const nextNode = {
    uid: item.uid,
    name: item.name,
    type: item.type,
    pathname: item.pathname,
    parentUid,
    // Index depth comes from the index itself, never the hydrated tree: keep an
    // already-indexed node's depth (the authoritative value from the indexer),
    // and derive a brand-new node's depth from its parent index node — the same
    // formula collectionIndexNodeAdded uses. This removes the last dependency on
    // the hydrated item.depth so the O(N^2) addDepth walk can go away.
    depth: currentNode ? currentNode.depth : (parentNode ? (parentNode.depth || 0) + 1 : 0),
    seq: item.seq,
    filename: item.filename,
    method: request.method || '',
    url: request.url || '',
    // Keep the examples marker: the indexer scanned it, hydration knows it.
    exampleCount: item.examples ? item.examples.length : (currentNode?.exampleCount || 0)
  };
  // Skip the write (and the index-object identity change it causes downstream)
  // when nothing visible changed — hydration re-upserts every loaded request.
  if (currentNode
    && currentNode.name === nextNode.name
    && currentNode.type === nextNode.type
    && currentNode.pathname === nextNode.pathname
    && currentNode.parentUid === nextNode.parentUid
    && currentNode.depth === nextNode.depth
    && currentNode.seq === nextNode.seq
    && currentNode.filename === nextNode.filename
    && currentNode.method === nextNode.method
    && currentNode.url === nextNode.url
    && (currentNode.exampleCount || 0) === nextNode.exampleCount) {
    return;
  }
  setIndexNode(index, nextNode);
  appendChildUid(index, parentUid, item.uid);
  // A genuinely new node (no prior node at this uid OR pathname) grows the
  // index — bump totalNodes incrementally (a migration/update reuses an
  // existing node, so it's net-zero). Reveal effects key on totalNodes to
  // re-attempt as the index fills; without this, hydrating/loading a single
  // file (e.g. save-as) never re-ran the ancestor-expand + scroll, so a nested
  // target folder stayed collapsed and the row was never revealed.
  if (!existingNode) {
    index.totalNodes = (index.totalNodes || 0) + 1;
  }
};

const removeCollectionIndexNodeByPathname = (state, collectionUid, pathname, options = {}) => {
  const index = state.collectionIndexes?.[collectionUid];
  if (!index || !pathname) {
    return;
  }

  const rootNode = findIndexNodeByPathname(index, pathname);
  if (!rootNode) {
    return;
  }
  const nodesToRemove = options.recursive ? collectIndexSubtreeNodes(index, rootNode) : [rootNode];

  for (const node of nodesToRemove) {
    removeChildUid(index, node.parentUid, node.uid);
    delete index.childrenByParentUid[node.uid];
    deleteIndexNode(index, node);
  }

  index.totalNodes = Object.keys(index.nodesByUid).length;
  index.totalScanned = Math.min(index.totalScanned || index.totalNodes, index.totalNodes);
};

const getCollectionIndexSubtreeByPathname = (state, collectionUid, pathname) => {
  const index = state.collectionIndexes?.[collectionUid];
  if (!index || !pathname) {
    return [];
  }

  const rootNode = findIndexNodeByPathname(index, pathname);
  return rootNode ? collectIndexSubtreeNodes(index, rootNode) : [];
};

const addCollectionIndexSubtreeByPathname = (state, {
  sourceCollectionUid,
  targetCollectionUid,
  sourcePathname,
  targetPathname,
  rootName
}) => {
  const sourceIndex = state.collectionIndexes?.[sourceCollectionUid];
  const targetIndex = state.collectionIndexes?.[targetCollectionUid];
  if (!sourceIndex || !targetIndex || !sourcePathname || !targetPathname) {
    return;
  }

  const sourceNodes = getCollectionIndexSubtreeByPathname(state, sourceCollectionUid, sourcePathname);
  if (!sourceNodes.length) {
    return;
  }

  const normalizedSourcePathname = normalizeIndexPathKey(sourcePathname);
  const normalizedTargetPathname = normalizeIndexPathKey(targetPathname);
  const sourceRootNode = sourceNodes.find((node) => normalizeIndexPathKey(node.pathname) === normalizedSourcePathname) || sourceNodes[0];
  const targetParentPathname = path.dirname(normalizedTargetPathname);
  const targetParentNode = findIndexNodeByPathname(targetIndex, targetParentPathname);
  const targetParentUid = targetParentNode?.uid || null;
  const targetRootDepth = targetParentNode ? ((targetParentNode.depth || 0) + 1) : 0;
  const depthDelta = targetRootDepth - (sourceRootNode.depth || 0);
  const uidMap = new Map();

  sourceNodes.forEach((node) => {
    uidMap.set(node.uid, uuid());
  });

  const sortedNodes = [...sourceNodes].sort((a, b) => (a.depth || 0) - (b.depth || 0));
  for (const sourceNode of sortedNodes) {
    const normalizedNodePathname = normalizeIndexPathKey(sourceNode.pathname);
    const nextPathname = normalizedNodePathname === normalizedSourcePathname
      ? normalizedTargetPathname
      : normalizedNodePathname.replace(normalizedSourcePathname, normalizedTargetPathname);
    const isRootNode = sourceNode.uid === sourceRootNode.uid;
    const newUid = uidMap.get(sourceNode.uid);
    const parentUid = isRootNode ? targetParentUid : (uidMap.get(sourceNode.parentUid) || null);
    const existingNode = findIndexNodeByPathname(targetIndex, nextPathname);

    if (existingNode) {
      removeCollectionIndexNodeByPathname(state, targetCollectionUid, nextPathname, {
        recursive: sourceNode.type === 'folder'
      });
    }

    setIndexNode(targetIndex, {
      ...sourceNode,
      uid: newUid,
      parentUid,
      pathname: nextPathname,
      filename: path.basename(nextPathname),
      name: isRootNode && rootName ? rootName : sourceNode.name,
      depth: Math.max(0, (sourceNode.depth || 0) + depthDelta)
    });
    appendChildUid(targetIndex, parentUid, newUid);
  }

  targetIndex.totalNodes = Object.keys(targetIndex.nodesByUid).length;
  targetIndex.totalScanned = Math.max(targetIndex.totalScanned || 0, targetIndex.totalNodes);
};

const updateCollectionIndexNodePath = (node, previousPathname, nextPathname) => {
  const normalizedPreviousPathname = normalizeIndexPathKey(previousPathname);
  const normalizedNextPathname = normalizeIndexPathKey(nextPathname);
  const normalizedNodePathname = normalizeIndexPathKey(node.pathname);

  if (normalizedNodePathname === normalizedPreviousPathname || normalizedNodePathname.startsWith(`${normalizedPreviousPathname}${path.sep}`)) {
    node.pathname = normalizedNodePathname.replace(normalizedPreviousPathname, normalizedNextPathname);
    node.filename = path.basename(node.pathname);
  }
};

const moveCollectionIndexNodeByPathname = (state, collectionUid, sourcePathname, targetPathname) => {
  const index = state.collectionIndexes?.[collectionUid];
  if (!index || !sourcePathname || !targetPathname) {
    return;
  }

  const movedNode = findIndexNodeByPathname(index, sourcePathname);
  if (!movedNode) {
    return;
  }

  const previousParentUid = movedNode.parentUid || null;
  const previousPathname = movedNode.pathname;
  const nextParentPathname = path.dirname(targetPathname);
  const nextParentNode = findIndexNodeByPathname(index, nextParentPathname);
  const nextParentUid = nextParentNode?.uid || null;
  const nextDepth = nextParentNode ? ((nextParentNode.depth || 0) + 1) : 0;
  const depthDelta = nextDepth - (movedNode.depth || 0);

  if (previousParentUid !== nextParentUid) {
    removeChildUid(index, previousParentUid, movedNode.uid);
    appendChildUid(index, nextParentUid, movedNode.uid);
  }

  // Only the moved node and its descendants change — walk the subtree via
  // childrenByParentUid instead of scanning the whole index.
  for (const node of collectIndexSubtreeNodes(index, movedNode)) {
    const nodePreviousPathname = node.pathname;
    updateCollectionIndexNodePath(node, previousPathname, targetPathname);
    if (node.pathname !== nodePreviousPathname) {
      rekeyIndexNodePathname(index, node, nodePreviousPathname);
    }
    node.depth = Math.max(0, (node.depth || 0) + depthDelta);
    if (node.uid === movedNode.uid) {
      node.parentUid = nextParentUid;
    }
  }
};

